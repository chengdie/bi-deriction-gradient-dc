#!/usr/bin/env bash

QWEN_PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MODEL_PATH="${MODEL_PATH:-/mnt/gemininjceph3/geminicephfs/mmsearch-luban-universal/group_semantic_doc/user_awardcheng/qwen3.5-4b}"
DATA_DIR="${DATA_DIR:-$QWEN_PROJECT_ROOT/data}"
EXPERIMENT_OUTPUT_DIR="${EXPERIMENT_OUTPUT_DIR:-$QWEN_PROJECT_ROOT/out/qwen3.5-experiments}"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}"
export TOKENIZERS_PARALLELISM=false
export OMP_NUM_THREADS="${OMP_NUM_THREADS:-4}"
PYTHON_BIN="${PYTHON_BIN:-python}"
IFS=',' read -r -a QWEN_VISIBLE_GPUS <<< "$CUDA_VISIBLE_DEVICES"
TRAIN_NPROC="${TRAIN_NPROC:-${#QWEN_VISIBLE_GPUS[@]}}"
EVAL_NPROC="${EVAL_NPROC:-$TRAIN_NPROC}"
GRADIENT_NPROC="${GRADIENT_NPROC:-$TRAIN_NPROC}"
TRAIN_BATCH_SIZE="${TRAIN_BATCH_SIZE:-2}"
GLOBAL_BATCH_SIZE="${GLOBAL_BATCH_SIZE:-16}"
GRADIENT_CHECKPOINTING="${GRADIENT_CHECKPOINTING:-False}"
EVAL_BATCH_SIZE="${EVAL_BATCH_SIZE:-4}"
PREPROCESSING_NUM_WORKERS="${PREPROCESSING_NUM_WORKERS:-4}"
DATALOADER_NUM_WORKERS="${DATALOADER_NUM_WORKERS:-2}"
if [[ ! "$DATALOADER_NUM_WORKERS" =~ ^(0|[1-9][0-9]*)$ ]]; then
    printf 'DATALOADER_NUM_WORKERS must be a nonnegative integer.\n' >&2
    return 2
fi
for variable in TRAIN_NPROC EVAL_NPROC GRADIENT_NPROC TRAIN_BATCH_SIZE GLOBAL_BATCH_SIZE EVAL_BATCH_SIZE PREPROCESSING_NUM_WORKERS; do
    if [[ ! "${!variable}" =~ ^[1-9][0-9]*$ ]]; then
        printf '%s must be a positive integer.\n' "$variable" >&2
        return 2
    fi
done
if (( TRAIN_NPROC > ${#QWEN_VISIBLE_GPUS[@]} || EVAL_NPROC > ${#QWEN_VISIBLE_GPUS[@]} || GRADIENT_NPROC > ${#QWEN_VISIBLE_GPUS[@]} )); then
    printf 'Process counts exceed CUDA_VISIBLE_DEVICES.\n' >&2
    return 2
fi
if [[ -z "${GRADIENT_ACCUMULATION_STEPS:-}" ]]; then
    if (( GLOBAL_BATCH_SIZE % (TRAIN_NPROC * TRAIN_BATCH_SIZE) != 0 )); then
        printf 'GLOBAL_BATCH_SIZE must be divisible by TRAIN_NPROC * TRAIN_BATCH_SIZE.\n' >&2
        return 2
    fi
    GRADIENT_ACCUMULATION_STEPS=$(( GLOBAL_BATCH_SIZE / (TRAIN_NPROC * TRAIN_BATCH_SIZE) ))
fi
if [[ ! "$GRADIENT_ACCUMULATION_STEPS" =~ ^[1-9][0-9]*$ ]]; then
    printf 'GRADIENT_ACCUMULATION_STEPS must be a positive integer.\n' >&2
    return 2
fi

TASK="${TASK:-mmlu}"
SELECTION_SEED="${SELECTION_SEED:-3}"
TRAIN_SEED="${TRAIN_SEED:-0}"
NUM_TRAIN_EPOCHS="${NUM_TRAIN_EPOCHS:-1}"
MAX_STEPS="${MAX_STEPS:--1}"
MAX_SEQ_LENGTH="${MAX_SEQ_LENGTH:-1024}"
LEARNING_RATE="${LEARNING_RATE:-1e-5}"
LORA_R="${LORA_R:-16}"
LORA_ALPHA="${LORA_ALPHA:-64}"
TRAIN_PERCENTAGE="${TRAIN_PERCENTAGE:-1.0}"

EVAL_SEED="${EVAL_SEED:-42}"
EVAL_MAX_LENGTH="${EVAL_MAX_LENGTH:-8192}"
EVAL_MAX_NEW_TOKENS="${EVAL_MAX_NEW_TOKENS:-512}"
WARMUP_EPOCHS="${WARMUP_EPOCHS:-4}"
WARMUP_MAX_STEPS="${WARMUP_MAX_STEPS:--1}"
WARMUP_PERCENTAGE="${WARMUP_PERCENTAGE:-0.05}"
PROJECTION_DIM="${PROJECTION_DIM:-8192}"
GRADIENT_MAX_LENGTH="${GRADIENT_MAX_LENGTH:-4096}"
